"""Build torque/worker/src/points.mjs (id, name, village) from out/points.json.

Run after scoring/export_points.py. The output is generated, so it is not committed.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPE = re.compile(r"\b(borehole|shallow|well|water|scheme|solar|piped|gravity|primary|secondary|school|health|centre|center|"
                  r"dispensary|hand|dug|kiosk|tap|stand|spring|tank|rainwater|pump|protected|\d+)\b", re.I)

rows = []
for p in json.loads((ROOT / "out/points.json").read_text()):
    village = re.sub(r"\s+", " ", TYPE.sub(" ", p["n"])).strip().lower()
    rows.append([p["id"], p["n"], village])

out = ROOT / "torque/worker/src/points.mjs"
out.write_text("// Generated by torque/gen_points.py from out/points.json. Do not edit.\nexport const POINTS = "
               + json.dumps(rows, separators=(",", ":")) + ";\n")
print(f"{len(rows)} water points -> {out.relative_to(ROOT)}")
